"""Profile the raw Olist tables and write the results to docs/data-profile.md.

Three kinds of checks:
  1. Column profile: type, % null, approx distinct values, min/max (DuckDB SUMMARIZE)
  2. Key checks: is each table's expected primary key really unique and non-null?
  3. Relationship checks: do foreign keys point at rows that exist (no "orphans")?

Read-only, safe to re-run, and safe while the DuckDB UI is open.

Usage (from the repo root, with the venv active):
    python scripts/profile_raw.py
"""

from datetime import date
from pathlib import Path

import duckdb

REPO_ROOT = Path(__file__).resolve().parent.parent
DB_PATH = REPO_ROOT / "warehouse" / "olist.duckdb"
OUT_PATH = REPO_ROOT / "docs" / "data-profile.md"

# The column(s) we expect to uniquely identify a row in each table.
EXPECTED_KEYS = {
    "customers": ["customer_id"],
    "orders": ["order_id"],
    "order_items": ["order_id", "order_item_id"],
    "order_payments": ["order_id", "payment_sequential"],
    "order_reviews": ["review_id"],
    "products": ["product_id"],
    "sellers": ["seller_id"],
    "product_category_name_translation": ["product_category_name"],
    "geolocation": ["geolocation_zip_code_prefix"],
}

# (child table, child column, parent table, parent column)
RELATIONSHIPS = [
    ("orders", "customer_id", "customers", "customer_id"),
    ("order_items", "order_id", "orders", "order_id"),
    ("order_items", "product_id", "products", "product_id"),
    ("order_items", "seller_id", "sellers", "seller_id"),
    ("order_payments", "order_id", "orders", "order_id"),
    ("order_reviews", "order_id", "orders", "order_id"),
    ("products", "product_category_name", "product_category_name_translation", "product_category_name"),
    ("customers", "customer_zip_code_prefix", "geolocation", "geolocation_zip_code_prefix"),
    ("sellers", "seller_zip_code_prefix", "geolocation", "geolocation_zip_code_prefix"),
]


def cell(value, width: int = 30) -> str:
    """Format a value for a markdown table cell: short, single-line, no pipes."""
    if value is None:
        return ""
    text = str(value).replace("|", "/").replace("\n", " ").replace("\r", " ")
    return text if len(text) <= width else text[: width - 1] + "…"


def profile_columns(con, table: str) -> list[str]:
    rows = con.execute(
        f"select column_name, column_type, null_percentage, approx_unique, min, max "
        f"from (summarize raw.{table})"
    ).fetchall()
    lines = [
        "| Column | Type | % null | ~Distinct | Min | Max |",
        "|---|---|---:|---:|---|---|",
    ]
    for name, col_type, null_pct, approx_unique, min_v, max_v in rows:
        lines.append(
            f"| {name} | {col_type} | {float(null_pct):.1f} | {approx_unique:,} "
            f"| {cell(min_v)} | {cell(max_v)} |"
        )
    return lines


def check_key(con, table: str, cols: list[str]) -> tuple[int, int, int]:
    """Return (total rows, distinct key values, rows with a null key)."""
    col_list = ", ".join(cols)
    any_null = " or ".join(f"{c} is null" for c in cols)
    total, distinct_keys = con.execute(
        f"select (select count(*) from raw.{table}), "
        f"(select count(*) from (select distinct {col_list} from raw.{table}))"
    ).fetchone()
    nulls = con.execute(f"select count(*) from raw.{table} where {any_null}").fetchone()[0]
    return total, distinct_keys, nulls


def check_relationship(con, child, child_col, parent, parent_col) -> tuple[int, int]:
    """Return (child rows with a non-null FK, rows whose FK has no matching parent)."""
    return con.execute(
        f"""
        select count(*),
               count(*) filter (where p.{parent_col} is null)
        from raw.{child} c
        left join (select distinct {parent_col} from raw.{parent}) p
          on c.{child_col} = p.{parent_col}
        where c.{child_col} is not null
        """
    ).fetchone()


def main() -> None:
    con = duckdb.connect(str(DB_PATH), read_only=True)
    tables = [r[0] for r in con.execute(
        "select table_name from information_schema.tables "
        "where table_schema = 'raw' order by table_name"
    ).fetchall()]

    out = [
        "# Raw Data Profile",
        "",
        f"_Generated by `scripts/profile_raw.py` on {date.today()}. Do not edit by hand; re-run the script._",
        "",
        "## 1. Key checks",
        "",
        "Is each table's expected primary key unique and never null?",
        "",
        "| Table | Expected key | Rows | Distinct keys | Null keys | Result |",
        "|---|---|---:|---:|---:|---|",
    ]
    for table, cols in EXPECTED_KEYS.items():
        total, distinct_keys, nulls = check_key(con, table, cols)
        ok = total == distinct_keys and nulls == 0
        result = "✅ unique" if ok else f"❌ {total - distinct_keys:,} duplicate rows"
        out.append(
            f"| {table} | {', '.join(cols)} | {total:,} | {distinct_keys:,} | {nulls:,} | {result} |"
        )

    out += [
        "",
        "## 2. Relationship checks",
        "",
        "Does every foreign key value exist in its parent table? Orphans break joins and drop rows.",
        "",
        "| Child → Parent | Rows checked | Orphans | Result |",
        "|---|---:|---:|---|",
    ]
    for child, child_col, parent, parent_col in RELATIONSHIPS:
        checked, orphans = check_relationship(con, child, child_col, parent, parent_col)
        result = "✅" if orphans == 0 else f"⚠️ {orphans / checked:.2%} orphaned"
        out.append(
            f"| {child}.{child_col} → {parent}.{parent_col} | {checked:,} | {orphans:,} | {result} |"
        )

    out += ["", "## 3. Column profiles", "",
            "`~Distinct` is approximate (fast estimate); key checks above use exact counts.", ""]
    for table in tables:
        out += [f"### raw.{table}", ""] + profile_columns(con, table) + [""]

    con.close()
    OUT_PATH.write_text("\n".join(out), encoding="utf-8")
    print(f"Wrote {OUT_PATH.relative_to(REPO_ROOT)}")


if __name__ == "__main__":
    main()
